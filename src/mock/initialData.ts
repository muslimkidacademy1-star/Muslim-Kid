function generateFullAcademyStudents(): Student[] {
  const list: Student[] = [...INITIAL_STUDENTS];
  const targetCount = 184;
  let idIndex = 22;

  while (list.length < targetCount) {
    const fName = STUDENT_FIRST_NAMES[Math.floor(Math.random() * STUDENT_FIRST_NAMES.length)];
    const lName = STUDENT_LAST_NAMES[Math.floor(Math.random() * STUDENT_LAST_NAMES.length)];
    const fullName = `${fName} ${lName}`;
    const teacher = INITIAL_TEACHERS[Math.floor(Math.random() * INITIAL_TEACHERS.length)];
    const phone = `05${Math.floor(10000000 + Math.random() * 90000000)}`;
    const fee = [250, 300, 350, 400][Math.floor(Math.random() * 4)];

    // status distribution: 8 on vacation, 14 overdue, rest active
    let status: 'active' | 'vacation' = 'active';
    let lastReportDate = getRelativeDateString(3);
    let notes = 'طالب منتظم بحلقات التسميع';
    let vacStart: string | undefined;
    let vacEnd: string | undefined;

    const vacCount = list.filter(s => s.status === 'vacation').length;
    const overdueCount = list.filter(s => {
      const parts = s.lastReportDate.split('-');
      if (parts.length === 3) {
        const d = new Date(parseInt(parts[0], 10), parseInt(parts[1], 10) - 1, parseInt(parts[2], 10));
        const diffDays = Math.floor((Date.now() - d.getTime()) / (1000 * 3600 * 24));
        return diffDays > 30 && s.status === 'active';
      }
      return false;
    }).length;

    if (vacCount < 8 && Math.random() < 0.1) {
      status = 'vacation';
      vacStart = getRelativeDateString(5);
      vacEnd = getFutureDateString(14);
      notes = 'إجازة سفر عائلية معتمدة';
      lastReportDate = getRelativeDateString(12);
    } else if (overdueCount < 14 && Math.random() < 0.15) {
      status = 'active';
      // Some warning (26-30 days), some overdue (>30 days)
      const isRedOverdue = Math.random() > 0.4;
      const daysOverdue = isRedOverdue
        ? Math.floor(31 + Math.random() * 8) // 31 to 38 days ago (>30 red alert)
        : Math.floor(26 + Math.random() * 5); // 26 to 30 days ago (>25 yellow warning)
      lastReportDate = getRelativeDateString(daysOverdue);
      notes = isRedOverdue
        ? 'تجاوز 30 يوماً بدون تقرير 8 حصص (تنبيه أحمر)'
        : 'مر أكثر من 25 يوماً على آخر تقرير (تحذير أصفر)';
    } else {
      status = 'active';
      const daysRecent = Math.floor(Math.random() * 20); // 0 to 19 days ago (regular cycle)
      lastReportDate = getRelativeDateString(daysRecent);
      notes = 'مستوى متميز، يتابع بانتظام في حلقة القرآن';
    }

    const scheduleDayOptions = [
      [getTodayArabicWeekday(), 'الثلاثاء', 'الخميس'],
      ['الأحد', getTodayArabicWeekday(), 'الأربعاء'],
      ['السبت', 'الإثنين', 'الأربعاء'],
      ['الأحد', 'الثلاثاء', 'الخميس'],
      ['الإثنين', 'الخميس'],
    ];
    const times = ['04:00 م', '04:30 م', '05:15 م', '06:00 م', '06:45 م', '07:30 م'];
    const chosenDays = scheduleDayOptions[idIndex % scheduleDayOptions.length];
    const chosenTime = times[idIndex % times.length] + ' بتوقيت مكة';
    const cycleCount = (idIndex % 8) + 1; // 1 to 8

    list.push({
      id: `s${idIndex}`,
      name: fullName,
      teacherId: teacher.id,
      parentPhone: phone,
      subscriptionFee: fee,
      subscriptionDate: getRelativeDateString(80),
      lastReportDate,
      status,
      vacationStartDate: vacStart,
      vacationEndDate: vacEnd,
      vacationType: status === 'vacation' ? 'إجازة معتمدة' : undefined,
      notes,
      surahProgress: `${teacher.circleName} • ${teacher.track}`,
      initials: fullName.charAt(0),
      scheduleDays: chosenDays,
      sessionTime: chosenTime,
      meetingUrl: `https://zoom.us/j/92048${1000 + idIndex}`,
      currentCycleSessionsCount: cycleCount,
    });

    idIndex++;
  }

  return list;
}

